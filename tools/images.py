#!/usr/bin/env python3
"""The translated images of Gyrinus II and the steps that build them.

    images.py analyse   SuperSpider (superspider analyse --full) on every image:
                        analysis/<name>.json; analysis/<name>.roots, if there,
                        adds entry points
    images.py roots LOG...
                        merges the gap entries of --trace-gaps runs (libroger's
                        untranslated.log) into analysis/<name>.roots
    images.py gen       superspider gen for every image -> recomp/gen/<name>/,
                        plus recomp/gen/modules.inc (game.c's module list)

Images (the 2MB+ !Run path; the 1MB variants are not used):
  mcode      Code.MCode: the game. An absolute file loaded at &7F800 and
             entered at &8BD08 (its execution address).
  v_<name>   the 16 sample voice modules Soundfx.Loadfx2Meg RMLoads, in that
             order, at the RMA addresses fixed here.
  coco       the CoconizerSong music player modules (Musik.TitleTrak and
             Gyrn2Mapz Musix.Level1-5), which the game RMRuns and RMKills
             itself. Their code is the same (only song data differs) and only
             one is loaded at a time, so they share one translation and one
             address, translated from TitleTrak.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(HERE)
EXT = os.path.join(TOP, 'game')                 # !Gyrinus2, !Gyrn2Mapz, ... (recipe.json)
SS = os.environ.get('SUPERSPIDER', os.path.expanduser('~/stuff/superspider'))

MCODE = ('!Gyrinus2/Code/MCode,0007f800-00000000', 0x7F800, 0x8BD08)
VOICES = 'Aargh! Lazer GotBonus Explo1 Explo2 Explo3 Pulse SmallBonus OOZY9MM Hey! Boogaloo TimeToDie TwighL Water IllBeBack NowtPersnl'.split()
SONGS = ['!Gyrinus2/Musik/TitleTrak,fffffa44-00000000'] + [
    '!Gyrn2Mapz/Musix/' + f for f in sorted(os.listdir(os.path.join(EXT, '!Gyrn2Mapz/Musix')))]
COCO_BASE = 0x1840000


def find(d, leaf):
    for f in os.listdir(os.path.join(EXT, d)):
        if f.split(',')[0].lower() == leaf.lower():
            return d + '/' + f
    raise SystemExit('not found: %s/%s' % (d, leaf))


def images():
    """(name, path relative to game/, base, exec or None, is module)"""
    out = [('mcode', MCODE[0], MCODE[1], MCODE[2], False)]
    base = 0x1800000
    for v in VOICES:
        p = find('!Gyrinus2/Soundfx', v)
        out.append(('v_' + v.rstrip('!').lower(), p, base, None, True))
        base = (base + os.path.getsize(os.path.join(EXT, p)) + 0xFFF) & ~0xFFF
    assert base <= COCO_BASE
    out.append(('coco', SONGS[0], COCO_BASE, None, True))
    return out


def run(cmd):
    print('+', ' '.join(cmd), flush=True)
    subprocess.run(cmd, check=True)


def analyse():
    subprocess.run(['dune', 'build'], cwd=SS, check=True)
    exe = os.path.join(SS, '_build/default/bin/main.exe')
    an = os.path.join(TOP, 'analysis')
    os.makedirs(an, exist_ok=True)
    for name, path, base, exe_addr, module in images():
        img = os.path.join(EXT, path)
        cmd = [exe, 'analyse', img, '%x' % base, '--full', '-o', os.path.join(an, name + '.json')]
        rf = os.path.join(an, name + '.roots')
        if os.path.exists(rf):
            cmd += ['--roots', rf]
        cmd += ['--module'] if module else ['--exec', '%x' % exe_addr]
        run(cmd)


def roots(logs):
    """Merges the gap entries the --trace-gaps runs logged in LOGS (libroger's
    untranslated.log) into analysis/<name>.roots, for the next analyse."""
    an = os.path.join(TOP, 'analysis')
    for name, path, base, exe_addr, module in images():
        run([sys.executable, os.path.join(SS, 'tools/gap_roots.py'), os.path.join(EXT, path),
             '%x' % base, os.path.join(an, name + '.roots')] + logs)


def gen():
    exe = os.path.join(SS, '_build/default/bin/main.exe')
    rc = os.path.join(TOP, 'recomp')
    an = os.path.join(TOP, 'analysis')
    mods = []
    for k, (name, path, base, exe_addr, module) in enumerate(images()):
        tab = 'recomp' if name == 'mcode' else 'recomp_' + name
        prefix = 'F' if name == 'mcode' else 'M%d' % k
        run([exe, 'gen', os.path.join(EXT, path), '%x' % base, os.path.join(an, name + '.json'),
             '--c', os.path.join(rc, 'gen', name), '--prefix=' + prefix, '--tabprefix=' + tab, '--files=%d' % (8 if name == 'mcode' else 1)]
            + (['--covtag=%s' % chr(ord('A') + k)] if module else []))
        if name == 'coco':
            for s in SONGS:
                mods.append((s, tab, 1))
        elif module:
            mods.append((path, tab, 0))
    with open(os.path.join(rc, 'gen', 'modules.inc'), 'w') as f:
        f.write('/* generated by ../tools/images.py - the modules, for game.c */\n')
        for tab in sorted({t for _, t, _ in mods}):
            f.write('extern const struct roger_image %s_image;\n' % tab)
        f.write('static const struct roger_module modules[] = {\n')
        for path, tab, od in mods:
            f.write('    {"../game/%s", &%s_image, %d},\n' % (path, tab, od))
        f.write('    {NULL, NULL, 0}};\n')


if __name__ == '__main__':
    if sys.argv[1] == 'roots':
        roots(sys.argv[2:] or ['untranslated.log'])
    else:
        {'analyse': analyse, 'gen': gen}[sys.argv[1]]()
